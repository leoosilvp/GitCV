function normalizeKey(name) {
    return name?.trim().toLowerCase() ?? ""
}

function faviconUrl(domain) {
    return `${FAVICON_BASE}?sz=128&domain=${domain}`
}

export function getCompanyLogo(name) {
    const key = normalizeKey(name)
    if (!key) return null

    if (COMPANY_LOGOS[key]) return COMPANY_LOGOS[key]

    const domain = NEWS_OUTLET_DOMAINS[key]
    if (domain) return faviconUrl(domain)

    return null
}